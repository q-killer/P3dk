import * as ort from 'https://cdn.jsdelivr.net/npm/onnxruntime-web@1.19.0/dist/ort.esm.min.js';

// ── Runtime state ─────────────────────────────────────────────────────────────
let encSession = null, decSession = null, nerfSession = null;
let SHAPES = null;

// ── Status helper ─────────────────────────────────────────────────────────────
const status = (stage, msg) => self.postMessage({type:'status', stage, msg});

// ── ORT session factory ───────────────────────────────────────────────────────
async function loadSession(url) {
  // Try WebGPU first — 5-10× faster than WASM on supported devices
  // Fall back to WASM silently if WebGPU unavailable
  for (const ep of ['webgpu', 'wasm']) {
    try {
      const sess = await ort.InferenceSession.create(url, {
        executionProviders: [ep],
        graphOptimizationLevel: 'all',
        // Enable memory pattern reuse across runs
        enableMemPattern: true,
        enableCpuMemArena: true,
      });
      return sess;
    } catch(e) {
      if (ep === 'wasm') throw e; // both failed
    }
  }
}

// ── Stage 0: Load models ──────────────────────────────────────────────────────
async function init(baseUrl, shapes) {
  SHAPES = shapes;
  status(0, 'Loading encoder (~22MB)…');
  encSession  = await loadSession(`${baseUrl}/encoder_q8.onnx`);

  status(0, 'Loading decoder (~75MB)…');
  decSession  = await loadSession(`${baseUrl}/decoder_q8.onnx`);

  status(0, 'Loading NeRF MLP (~2MB)…');
  nerfSession = await loadSession(`${baseUrl}/nerf_mlp_q8.onnx`);

  self.postMessage({type:'ready'});
}

// ── Stage 1: Preprocess + Encode ──────────────────────────────────────────────
// Bilinear resize to 224×224 + ImageNet normalisation
function preprocessImageData(imageData) {
  const {data, width, height} = imageData;
  const [mR,mG,mB] = SHAPES.imagenet_mean;
  const [sR,sG,sB] = SHAPES.imagenet_std;
  const tensor = new Float32Array(3 * 224 * 224);

  for (let y = 0; y < 224; y++) {
    for (let x = 0; x < 224; x++) {
      // Bilinear sample from source
      const sx = x / 223 * (width  - 1);
      const sy = y / 223 * (height - 1);
      const x0 = Math.floor(sx), y0 = Math.floor(sy);
      const x1 = Math.min(x0+1, width-1), y1 = Math.min(y0+1, height-1);
      const wx = sx - x0, wy = sy - y0;

      const i00 = (y0*width + x0)*4, i10 = (y0*width + x1)*4;
      const i01 = (y1*width + x0)*4, i11 = (y1*width + x1)*4;

      const r = (data[i00]*(1-wx)*(1-wy) + data[i10]*wx*(1-wy) +
                 data[i01]*(1-wx)*wy     + data[i11]*wx*wy) / 255;
      const g = (data[i00+1]*(1-wx)*(1-wy) + data[i10+1]*wx*(1-wy) +
                 data[i01+1]*(1-wx)*wy     + data[i11+1]*wx*wy) / 255;
      const b = (data[i00+2]*(1-wx)*(1-wy) + data[i10+2]*wx*(1-wy) +
                 data[i01+2]*(1-wx)*wy     + data[i11+2]*wx*wy) / 255;

      const idx = y*224 + x;
      tensor[0*224*224 + idx] = (r - mR) / sR;
      tensor[1*224*224 + idx] = (g - mG) / sG;
      tensor[2*224*224 + idx] = (b - mB) / sB;
    }
  }
  return tensor;
}

async function encode(imageTensor) {
  const input = new ort.Tensor('float32', imageTensor, [1, 3, 224, 224]);
  const out = await encSession.run({image: input});
  return out.tokens; // OrtTensor (1, N_tok, D)
}

// ── Stage 2: Decode to triplane ───────────────────────────────────────────────
async function decode(tokensTensor) {
  const out = await decSession.run({image_tokens: tokensTensor});
  return out.triplane; // OrtTensor (1, 3*C, H, W)
}

// ── Stage 3: Triplane sampling + NeRF MLP ────────────────────────────────────
// Bilinear sample one plane at position (u,v) ∈ [0, dim-1] for all channels C.
// plane: Float32Array of shape [C, H, W]
function samplePlane(plane, C, H, W, u, v, out, outOff) {
  const u0 = Math.max(0, Math.min(W-2, u|0));
  const v0 = Math.max(0, Math.min(H-2, v|0));
  const wu = u - u0, wv = v - v0;
  const w00 = (1-wu)*(1-wv), w10 = wu*(1-wv);
  const w01 = (1-wu)*wv,     w11 = wu*wv;
  for (let c = 0; c < C; c++) {
    const base = c * H * W;
    out[outOff + c] =
      plane[base + v0*W + u0] * w00 +
      plane[base + v0*W + u0+1] * w10 +
      plane[base + (v0+1)*W + u0] * w01 +
      plane[base + (v0+1)*W + u0+1] * w11;
  }
}

// Sample all three triplane planes for a batch of 3D query points.
// triplane: Float32Array (1, 3*C, H, W) — flat, row-major
// points:   Float32Array (N, 3)          — xyz in [-1, 1]
// returns:  Float32Array (N, 3*C)
function sampleTriplane(triplane, C, H, W, points) {
  const N = points.length / 3;
  const features = new Float32Array(N * 3 * C);
  // triplane layout: plane0=[0..C*H*W), plane1=[C*H*W..2*C*H*W), plane2=[2*C*H*W..)
  const planeStride = C * H * W;
  const p0 = triplane.subarray(0, planeStride);              // XY plane
  const p1 = triplane.subarray(planeStride, 2*planeStride);  // XZ plane
  const p2 = triplane.subarray(2*planeStride, 3*planeStride);// YZ plane

  for (let i = 0; i < N; i++) {
    const x = points[i*3], y = points[i*3+1], z = points[i*3+2];
    const u_xy = (x+1)*0.5*(W-1),  v_xy = (y+1)*0.5*(H-1);
    const u_xz = (x+1)*0.5*(W-1),  v_xz = (z+1)*0.5*(H-1);
    const u_yz = (y+1)*0.5*(W-1),  v_yz = (z+1)*0.5*(H-1);
    const off = i * 3 * C;
    samplePlane(p0, C, H, W, u_xy, v_xy, features, off);
    samplePlane(p1, C, H, W, u_xz, v_xz, features, off + C);
    samplePlane(p2, C, H, W, u_yz, v_yz, features, off + 2*C);
  }
  return features;
}

