const EDGE_TABLE = buildEdgeTable();
const TRI_TABLE  = buildTriTable();

// Edge vertex coordinates: each edge connects two corners
// Corner i = (i&1, (i>>1)&1, (i>>2)&1)
const EDGE_VERTS = [
  [0,1],[1,2],[2,3],[3,0], // bottom face
  [4,5],[5,6],[6,7],[7,4], // top face
  [0,4],[1,5],[2,6],[3,7]  // vertical edges
];

function marchingCubes(density, RES, iso) {
  const vertices = [];
  const indices  = [];
  let vIdx = 0;

  // Vertex deduplication (simple hash → index)
  const vCache = new Map();

  function addVert(x, y, z) {
    const key = `${x.toFixed(5)},${y.toFixed(5)},${z.toFixed(5)}`;
    if (vCache.has(key)) return vCache.get(key);
    const i = vIdx++;
    vertices.push(x, y, z);
    vCache.set(key, i);
    return i;
  }

  function lerp(val0, val1, p0, p1) {
    // Interpolate along one axis between two corners
    if (Math.abs(iso - val0) < 1e-6) return p0;
    if (Math.abs(iso - val1) < 1e-6) return p1;
    const t = (iso - val0) / (val1 - val0);
    return p0 + t * (p1 - p0);
  }

  const scale = 2.0 / (RES - 1); // map grid coords to [-1, 1]

  for (let iz = 0; iz < RES - 1; iz++) {
    for (let iy = 0; iy < RES - 1; iy++) {
      for (let ix = 0; ix < RES - 1; ix++) {
        // 8 corners of the cube
        const corners = [
          [ix,   iy,   iz  ],
          [ix+1, iy,   iz  ],
          [ix+1, iy+1, iz  ],
          [ix,   iy+1, iz  ],
          [ix,   iy,   iz+1],
          [ix+1, iy,   iz+1],
          [ix+1, iy+1, iz+1],
          [ix,   iy+1, iz+1],
        ];
        const vals = corners.map(([cx,cy,cz]) =>
          density[cz * RES * RES + cy * RES + cx]);

        // Cube index: bit i set if corner i > iso
        let cubeIdx = 0;
        for (let i = 0; i < 8; i++) if (vals[i] > iso) cubeIdx |= (1 << i);

        if (cubeIdx === 0 || cubeIdx === 255) continue;

        const edgeMask = EDGE_TABLE[cubeIdx];
        const edgeVerts = new Array(12);

        for (let e = 0; e < 12; e++) {
          if (!(edgeMask & (1 << e))) continue;
          const [c0, c1] = EDGE_VERTS[e];
          const [cx0, cy0, cz0] = corners[c0];
          const [cx1, cy1, cz1] = corners[c1];
          const v0 = vals[c0], v1 = vals[c1];
          const x = lerp(v0, v1, cx0, cx1) * scale - 1;
          const y = lerp(v0, v1, cy0, cy1) * scale - 1;
          const z = lerp(v0, v1, cz0, cz1) * scale - 1;
          edgeVerts[e] = addVert(x, y, z);
        }

        // Emit triangles
        const triBase = cubeIdx * 16;
        for (let t = 0; t < 16; t += 3) {
          if (TRI_TABLE[triBase + t] === -1) break;
          indices.push(
            edgeVerts[TRI_TABLE[triBase + t]],
            edgeVerts[TRI_TABLE[triBase + t + 1]],
            edgeVerts[TRI_TABLE[triBase + t + 2]]
          );
        }
      }
    }
  }

  return {
    vertices: new Float32Array(vertices),
    indices:  new Uint32Array(indices)
  };
}

// ── Main reconstruction pipeline ──────────────────────────────────────────────
async function reconstruct(imageData) {
  if (!encSession || !decSession || !nerfSession) {
    self.postMessage({type:'error', msg:'Models not loaded — call init first'});
    return;
  }

  const {C, triplane_H: H, triplane_W: W, mc_threshold} = SHAPES;
  const RES = 64;

  // Stage 1 — encode
  status(1, 'Stage 1/4 — encoding image…');
  const imgTensor = preprocessImageData(imageData);
  const tokens = await encode(imgTensor);

  // Stage 2 — decode to triplane
  status(2, 'Stage 2/4 — decoding to triplane…');
  const triplane = await decode(tokens);
  // Flatten (1, 3C, H, W) → (3C, H, W)
  const triData = triplane.data;

  // Stage 3 — sample density grid
  status(3, 'Stage 3/4 — querying NeRF density…');
  const N = RES * RES * RES;
  const density = new Float32Array(N);

  // Build all query points
  const allPoints = new Float32Array(N * 3);
  let idx = 0;
  for (let iz = 0; iz < RES; iz++)
  for (let iy = 0; iy < RES; iy++)
  for (let ix = 0; ix < RES; ix++) {
    allPoints[idx++] = (ix / (RES-1)) * 2 - 1;
    allPoints[idx++] = (iy / (RES-1)) * 2 - 1;
    allPoints[idx++] = (iz / (RES-1)) * 2 - 1;
  }

  // Triplane wrapper for sampler (re-shape C from 3C)
  const tripData = triplane.data instanceof Float32Array
    ? triplane.data : new Float32Array(triplane.data);

  // Batch query — 4096 pts/batch
  const BATCH = 4096;
  for (let start = 0; start < N; start += BATCH) {
    const end = Math.min(start + BATCH, N);
    const pts = allPoints.slice(start * 3, end * 3);
    const feats = sampleTriplane(tripData, C, H, W, pts);
    const input = new ort.Tensor('float32', feats, [end-start, 3*C]);
    const result = await nerfSession.run({triplane_features: input});
    const out = result.density_rgb.data;
    for (let i = 0; i < end - start; i++) {
      density[start + i] = out[i * SHAPES.nerf_out_dim]; // first channel = density
    }
    // Progress update every ~16K points
    if ((start % 16384) === 0) {
      status(3, `Stage 3/4 — ${Math.round(start/N*100)}% density sampled…`);
    }
  }

  // Stage 4 — marching cubes
  status(4, 'Stage 4/4 — extracting mesh…');
  const {vertices, indices} = marchingCubes(density, RES, mc_threshold);

  self.postMessage(
    {type:'mesh', vertices, indices, triCount: indices.length / 3},
    [vertices.buffer, indices.buffer]
  );
}

// ── Message handler ───────────────────────────────────────────────────────────
self.onmessage = async (e) => {
  const {type} = e.data;
  try {
    if (type === 'init')        await init(e.data.baseUrl, e.data.shapes);
    else if (type === 'reconstruct') await reconstruct(e.data.imageData);
    else self.postMessage({type:'error', msg:`Unknown message type: ${type}`});
  } catch(err) {
    self.postMessage({type:'error', msg: err.message || String(err)});
  }
};
